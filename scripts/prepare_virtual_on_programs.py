#!/usr/bin/env python3
"""Offline translation of the local Virtual-On CPU programs into C++/Wasm.

Generated instruction bodies are specialized from the pinned MAME semantics;
no executable code is generated by the browser. Runtime guards preserve the
reference path for code not present in the local compilation corpus.
"""
import collections
import hashlib
import json
import re
import subprocess
import sys
import zipfile
from pathlib import Path
from prepare_virtual_on_aot import ROOT, OUT, MAME_COMMIT, original, replace_once
from prepare_cpu import prepare_cpu


def body_of(text, signature):
    """Pinned CPU functions close at column zero; nested blocks are indented."""
    start = text.index('\n{', text.index(signature)) + 2
    end = text.index('\n}', start)
    return text[start:end]


def cpu_source(cpu, extension='cpp'):
    return f'src/devices/cpu/{cpu}/{cpu}.{extension}'


def write_cpu(cpu, extension, text):
    path = ROOT / 'vendor/mame' / cpu_source(cpu, extension)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def trace_corpus():
    traces = list(OUT.glob('harvest-*-trace.json'))
    if not traces:
        raise SystemExit('Capture a local CPU trace first (TEST_HARVEST=1).')
    corpus = {cpu: collections.defaultdict(set) for cpu in ('i960', 'sharc', 'm68000')}
    for path in traces:
        data = json.loads(path.read_text())
        for cpu, rows in data['trace'].items():
            for pc, word in rows:
                corpus[cpu][pc].add(int(word, 16))
    return traces, corpus


def i960_semantics(source):
    body = body_of(source, 'void i960_cpu_device::execute_op(uint32_t opcode)')
    cases = list(re.finditer(r'^\t\t(case (0x[0-9a-f]+):|default:)', body, re.M))
    result = ['template<uint32_t opcode> __attribute__((always_inline)) inline void i960_cpu_device::aot_op() {',
              'uint32_t t1, t2; double t1f, t2f;']
    for case, following in zip(cases, cases[1:]):
        major = int(case.group(2), 16)
        code = body[case.end():following.start()]
        result.append(f'if constexpr ((opcode >> 24) == {major}) {{ do {{\n{code}\n}} while (false); }}')
    majors = [int(case.group(2), 16) for case in cases[:-1]]
    result.append('if constexpr (!(' + ' || '.join(f'(opcode >> 24) == {major}' for major in majors)
                  + ')) execute_op(opcode);')
    result.append('}')
    return '\n'.join(result)


def generate_i960(corpus):
    source = original(cpu_source('i960'))
    header = original(cpu_source('i960', 'h'))
    generated = ['// Local ROM-derived output. Do not commit.',
                 "// MAME BSD-3-Clause; copyright-holders:Farfetch'd, R. Belmont", i960_semantics(source)]
    profiles = {}
    for game in ('vonu', 'vonj'):
        directory = OUT / game
        # All observed entries seed direct-flow discovery, including previously
        # unseen indirect-call targets. RAM instructions are compiled with guards.
        seeds = directory / 'program-seeds.txt'
        seeds.write_text(''.join(f'{pc:x}\n' for pc in sorted(corpus) if pc < 0x200000))
        result = subprocess.run([str(OUT / 'i960-reach'), str(directory / 'program.bin'), str(seeds)],
                                text=True, capture_output=True, check=True)
        records = {int(pc, 16): {int(word, 16)} for pc, word in
                   (line.split() for line in result.stdout.splitlines())}
        binary = (directory / 'program.bin').read_bytes()
        for pc, words in corpus.items():
            if pc < 0x200000:
                # Preserve the selected region's actual instruction word.
                records[pc] = {int.from_bytes(binary[pc:pc+4], 'little')}
            else:
                records[pc] = set(words)
        profiles[game] = records
    groups, tables = {}, {}
    for game, records in profiles.items():
        pages = collections.defaultdict(dict)
        for pc, words in sorted(records.items()):
            if pc & 3 or pc >= 0x800000:
                continue
            pages[pc & ~63][pc] = words
        tables[game] = []
        for base, instructions in pages.items():
            identity = tuple((pc, tuple(sorted(words))) for pc, words in instructions.items())
            if identity not in groups:
                groups[identity] = len(groups)
            tables[game].append((base, groups[identity], instructions))
    for instructions, index in groups.items():
        generated.extend([f'template<> bool i960_cpu_device::aot_block<{index}>() {{',
            'bool ran = false;', 'while (m_icount > 0 && !m_stall_state.burst_mode) {',
            'switch (m_IP) {'])
        for pc, words in instructions:
            generated.append(f'case 0x{pc:x}: {{')
            # Model 2 maps this region as ROM with ignored writes. Validate all
            # compiled ROM words before enabling AOT, then eliminate instruction
            # fetch/decoding from the hot loop. RAM retains per-instruction guards.
            immutable = pc < 0x200000 and len(words) == 1
            if not immutable:
                generated.extend([f'const uint32_t actual = m_cache.read_dword(0x{pc:x});', 'switch (actual) {'])
            for word in words:
                if not immutable:
                    generated.append(f'case 0x{word:08x}u:')
                generated.extend([f'm_PIP = 0x{pc:x};',
                    'debugger_instruction_hook(m_PIP);', f'm_IP = 0x{pc+4:x}; m_stalled = false;',
                    f'aot_op<0x{word:08x}u>();', '++m_aot_hits; ran = true; break;'])
            if not immutable:
                generated.extend(['default: ++m_aot_guards; return ran;', '}', 'break;'])
            generated.append('}')
        generated.extend(['default: return ran;', '}', '}', 'return ran;', '}'])
    generated.extend(['void i960_cpu_device::aot_init() {', 'm_aot_blocks.resize(0x200000);',
                      'struct entry { uint32_t pc, word; aot_function run; };'])
    for game, entries in tables.items():
        generated.append(f'if (!strcmp(machine().system().name, "{game}")) {{')
        generated.append('static const entry entries[] = {')
        for _, index, instructions in entries:
            for pc, words in instructions.items():
                generated.append(f'{{0x{pc:x}, 0x{min(words):08x}u, &aot_thunk<{index}>}},')
        generated.extend(['};', 'for (const auto &entry : entries) {',
            'if (entry.pc < 0x200000 && m_cache.read_dword(entry.pc) != entry.word) {',
            '++m_aot_guards; m_aot_enabled = false; m_aot_blocks.clear(); return;', '}',
            'm_aot_blocks[entry.pc >> 2] = entry.run;', '}'])
        generated.append('}')
    generated.append('}')
    (OUT / 'virtual_on_i960_program.ipp').write_text('\n'.join(generated) + '\n')
    header = replace_once(header, '#pragma once', '#pragma once\n#include <vector>\n#include <unordered_set>')
    header = replace_once(header, '\tvoid do_ret();', '''\tvoid do_ret();
    using aot_function = bool (*)(i960_cpu_device *);
    std::vector<aot_function> m_aot_blocks;
    bool m_aot_enabled = false, m_aot_capture = false;
    std::unordered_set<uint32_t> m_aot_missing;
    uint32_t m_aot_hits = 0, m_aot_fallback = 0, m_aot_guards = 0, m_aot_events = 0;
    template<uint32_t opcode> void aot_op();
    template<unsigned block> bool aot_block();
    template<unsigned block> static bool aot_thunk(i960_cpu_device *cpu) { return cpu->aot_block<block>(); }
    void aot_init();''')
    source = replace_once(source, '#include "i960.h"', '#include "i960.h"\n#include <emscripten.h>')
    source = replace_once(source, 'void i960_cpu_device::execute_run()',
                          '#include "virtual_on_i960_program.ipp"\n\nvoid i960_cpu_device::execute_run()')
    source = replace_once(source, '\tspace(AS_PROGRAM).specific(m_program);', '''\tspace(AS_PROGRAM).specific(m_program);
    m_aot_enabled = EM_ASM_INT({ return Module['model2ProgramAot'] === true; }) &&
        (!strcmp(machine().system().name, "vonu") || !strcmp(machine().system().name, "vonj"));
    m_aot_capture = EM_ASM_INT({ return Module['model2AotCaptureMisses'] === true; });
    if (m_aot_enabled) aot_init();
    state_add(1000, "AOTENABLED", m_aot_enabled).noshow();
    state_add(1001, "AOTHITS", m_aot_hits).noshow();
    state_add(1002, "AOTFALLBACK", m_aot_fallback).noshow();
    state_add(1003, "AOTGUARD", m_aot_guards).noshow();
    state_add(1004, "AOTEVENTS", m_aot_events).noshow();''')
    source = replace_once(source, '\twhile(m_icount > 0) {\n\t\tm_PIP = m_IP;', '''\twhile(m_icount > 0) {
        if (m_aot_enabled && !debugger_enabled() && !m_stall_state.burst_mode &&
            m_IP < 0x800000 && !(m_IP & 3)) {
            const auto block = m_aot_blocks[m_IP >> 2];
            if (block && block(this)) continue;
        }
        if (m_stall_state.burst_mode) ++m_aot_events;
        else {
            ++m_aot_fallback;
            if (m_aot_enabled && m_aot_capture && m_aot_missing.insert(m_IP).second) {
                EM_ASM({
                    if (!Module['model2AotMisses']) Module['model2AotMisses'] = new Map();
                    Module['model2AotMisses'].set($0 >>> 0, ($1 >>> 0).toString(16).padStart(16, '0'));
                }, m_IP, m_cache.read_dword(m_IP));
            }
        }
\t\tm_PIP = m_IP;''')
    write_cpu('i960', 'cpp', source)
    write_cpu('i960', 'h', header)
    return {'blocks': len(groups), 'addresses': {game: len(rows) for game, rows in profiles.items()},
            'romValidation': 'All compiled ROM words checked at startup; Model 2 ROM writes are ignored'}


def generate_sharc(corpus):
    prepare_cpu(ROOT / 'vendor/mame')
    source = (ROOT / 'vendor/mame' / cpu_source('sharc')).read_text()
    header = (ROOT / 'vendor/mame' / cpu_source('sharc', 'h')).read_text()
    ops = original('src/devices/cpu/sharc/sharcops.hxx')
    table = original('src/devices/cpu/sharc/sharcops_table.cpp')
    descriptors = re.findall(r'\{\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*&adsp21062_device::(\w+)', table)
    # The upload image is stored as little-endian 48-bit words in main ROM.
    # Find its base using independent observed words, then verify every observed
    # address. The assembler's trailing copyright marks the end of its code.
    program = (OUT / 'vonu/program.bin').read_bytes()
    bases = collections.Counter()
    for pc, values in corpus.items():
        for word in values:
            if not word:
                continue
            needle = word.to_bytes(6, 'little')
            start = program.find(needle)
            if start >= 0 and program.find(needle, start + 1) < 0:
                bases[start - (pc - 0x20000) * 6] += 1
    image_base, votes = bases.most_common(1)[0]
    if votes < 100:
        raise RuntimeError('Could not identify a sufficiently corroborated SHARC upload image')
    marker = program.find(b'Copyright SEGA', image_base)
    if marker < 0:
        raise RuntimeError('Missing SHARC image end marker')
    count = (marker - image_base) // 6
    image = program[image_base:image_base + count * 6]
    for pc, values in corpus.items():
        offset = (pc - 0x20000) * 6
        if not 0 <= offset <= len(image) - 6 or values != {int.from_bytes(image[offset:offset+6], 'little')}:
            raise RuntimeError(f'SHARC image disagrees with trace at {pc:x}')
    japan = (OUT / 'vonj/program.bin').read_bytes()
    if japan[image_base:image_base + len(image)] != image:
        raise RuntimeError('USA/Japan SHARC program images differ; compile separate profiles')
    words = sorted({int.from_bytes(image[i:i+6], 'little') for i in range(0, len(image), 6)})
    (OUT / 'sharc-program.bin').write_bytes(image)
    generated = ['// Local uploaded-program-derived output. Do not commit.',
                 '// MAME BSD-3-Clause; copyright-holders:Ville Linde',
                 'template<uint32_t opcode> __attribute__((always_inline)) inline void adsp21062_device::aot_compute() {',
                 body_of(ops, 'void adsp21062_device::COMPUTE(uint32_t opcode)'), '}',
                 'template<uint64_t opcode> void adsp21062_device::aot_op() {']
    for index, (mask, bits, handler) in enumerate(descriptors):
        body = body_of(ops, f'void adsp21062_device::{handler}()')
        body = body.replace('m_core->opcode', 'opcode').replace('COMPUTE(compute);', 'aot_compute<compute>();')
        generated.append(f'{"if" if index == 0 else "else if"} constexpr (((opcode >> 32) & {mask}) == {bits}) {{\n{body}\n}}')
    generated.extend(['else sharcop_unimplemented();', '}', 'void adsp21062_device::aot_init() {',
                      'm_aot_cache.resize(0x10000);', 'm_aot_program = {'])
    for word in words:
        generated.append(f'{{0x{word:012x}ull, &aot_thunk<0x{word:012x}ull>}},')
    generated.extend(['};', '}'])
    generated.append('''extern "C" EMSCRIPTEN_KEEPALIVE void model2_aot_save_schema() {
        auto *machine = running_machine::emscripten_get_running_machine();
        if (!machine) return;
        EM_ASM({ Module['model2SaveSchema'] = []; });
        for (int index = 0; ; ++index) {
            void *base = nullptr;
            uint32_t size = 0, count = 0, blocks = 0, stride = 0;
            const char *name = machine->save().indexed_item(index, base, size, count, blocks, stride);
            if (!name) break;
            EM_ASM({ Module['model2SaveSchema'].push({name: UTF8ToString($0), size: $1, count: $2, blocks: $3}); },
                   name, size, count, blocks);
        }
    }''')
    (OUT / 'virtual_on_sharc_program.ipp').write_text('\n'.join(generated) + '\n')
    header = replace_once(header, '#pragma once', '#pragma once\n#include <unordered_map>\n#include <vector>')
    header = replace_once(header, '\tbool if_condition_always_true(int condition);', '''\tbool if_condition_always_true(int condition);
    using aot_function = void (*)(adsp21062_device *);
    struct aot_entry { uint64_t word = ~uint64_t(0); aot_function run = nullptr; };
    std::unordered_map<uint64_t, aot_function> m_aot_program;
    std::vector<aot_entry> m_aot_cache;
    bool m_aot_enabled = false;
    uint32_t m_aot_hits = 0, m_aot_fallback = 0, m_aot_changes = 0;
    template<uint64_t opcode> void aot_op();
    template<uint32_t opcode> void aot_compute();
    template<uint64_t opcode> static void aot_thunk(adsp21062_device *cpu) { cpu->aot_op<opcode>(); }
    void aot_init();''')
    source = replace_once(source, '#include "sharcops.hxx"',
                          '#include "sharcops.hxx"\n#include "virtual_on_sharc_program.ipp"')
    source = replace_once(source, '\t\t\tm_core->opcode = m_program.read_qword(m_core->pc);',
                          '\t\t\tconst uint32_t aot_pc = m_core->pc;\n\t\t\tm_core->opcode = m_program.read_qword(m_core->pc);')
    source = replace_once(source, '\tspace(AS_DATA).specific(m_data);', '''\tspace(AS_DATA).specific(m_data);
    m_aot_enabled = EM_ASM_INT({ return Module['model2ProgramAot'] === true && Module['model2SharcAot'] !== false; }) &&
        (!strcmp(machine().system().name, "vonu") || !strcmp(machine().system().name, "vonj"));
    if (m_aot_enabled) aot_init();
    state_add(1100, "AOTENABLED", m_aot_enabled).noshow();
    state_add(1101, "AOTHITS", m_aot_hits).noshow();
    state_add(1102, "AOTFALLBACK", m_aot_fallback).noshow();
    state_add(1103, "AOTCHANGES", m_aot_changes).noshow();''')
    source = replace_once(source, '\t\t\t(this->*m_sharc_op[(m_core->opcode >> 39) & 0x1ff])();', '''            aot_function compiled = nullptr;
            if (m_aot_enabled && !debugger_enabled() && aot_pc >= 0x20000 && aot_pc < 0x30000) {
                auto &entry = m_aot_cache[aot_pc - 0x20000];
                if (entry.word != m_core->opcode) {
                    if (entry.word != ~uint64_t(0)) ++m_aot_changes;
                    entry.word = m_core->opcode;
                    const auto found = m_aot_program.find(entry.word);
                    entry.run = found == m_aot_program.end() ? nullptr : found->second;
                }
                compiled = entry.run;
            }
            if (compiled) { ++m_aot_hits; compiled(this); }
            else { ++m_aot_fallback; (this->*m_sharc_op[(m_core->opcode >> 39) & 0x1ff])(); }''')
    write_cpu('sharc', 'cpp', source)
    write_cpu('sharc', 'h', header)
    return {'observedAddresses': len(corpus), 'imageInstructions': count, 'compiledInstructionWords': len(words),
            'romOffset': image_base, 'imageSha256': hashlib.sha256(image).hexdigest()}


def generate_m68000(corpus):
    source = original(cpu_source('m68000'))
    header = original(cpu_source('m68000', 'h'))
    full = original('src/devices/cpu/m68000/m68000-sdf.cpp')
    partial = original('src/devices/cpu/m68000/m68000-sdp.cpp')
    decode = original('src/devices/cpu/m68000/m68000-decode.cpp')
    descriptors = [tuple(int(value, 0) for value in row) for row in
                   re.findall(r'\{\s*(0x[0-9a-f]+),\s*(0x[0-9a-f]+),\s*(\d+)\s*\}', decode)]
    handlers = re.findall(r'&m68000_device::(\w+)', full.split('m68000_device::s_handlers_df[] = {', 1)[1])
    with zipfile.ZipFile(ROOT / 'roms/ready/vonu.zip') as archive:
        chip = archive.read(next(name for name in archive.namelist() if name.endswith('epr-18670.31')))
    image = bytearray(len(chip))
    image[0::2], image[1::2] = chip[1::2], chip[0::2]
    for pc, values in corpus.items():
        offset = pc - 0x600000
        if not 0 <= offset <= len(image) - 2 or values != {int.from_bytes(image[offset:offset+2], 'big')}:
            raise RuntimeError(f'Sound ROM disagrees with trace at {pc:x}')
    image_path = OUT / 'm68000-program.bin'
    image_path.write_bytes(image)
    seeds = OUT / 'm68000-seeds.txt'
    seeds.write_text(''.join(f'{pc:x}\n' for pc in sorted(corpus)))
    recomp = ROOT / 'vendor/daytona-recompiler'
    analyzer = OUT / 'm68000-reach'
    subprocess.run(['clang++', '-std=c++20', '-O2', '-I' + str(recomp / 'src'),
                    str(ROOT / 'scripts/m68000_reach.cpp'), str(recomp / 'src/m68k/decode.cpp'),
                    str(recomp / 'src/m68k/reach.cpp'), '-o', str(analyzer)], check=True)
    result = subprocess.run([str(analyzer), str(image_path), str(seeds)], text=True, capture_output=True, check=True)
    (OUT / 'm68000-reachable.txt').write_text(result.stdout)
    reached = {int(pc, 16): int(word, 16) for pc, word in (line.split() for line in result.stdout.splitlines())}
    words = sorted(set(reached.values()) | set.union(*corpus.values()))
    programs = {}
    for word in words:
        matches = [state for bits, mask, state in descriptors if mask and word & mask == bits]
        if not matches or (len(matches) != 1 and word & 0xf0ff != 0x6000):
            raise RuntimeError(f'Unambiguous 68000 decode required: {word:04x}: {matches}')
        programs[word] = (matches[0], handlers[matches[0]])
    generated = ['// Local sound-program-derived output. Do not commit.',
                 '// MAME BSD-3-Clause; copyright-holders:Olivier Galibert',
                 'namespace { bool sound_aot_enabled = false;',
                 'uint32_t sound_aot_hits = 0, sound_aot_fallback = 0, sound_aot_partial = 0, sound_aot_events = 0; }']
    for mode, text in [('full', full), ('partial', partial)]:
        generated.append(f'template<uint16_t opcode, unsigned state> void m68000_device::aot_{mode}() {{')
        used = {}
        for state, handler in programs.values():
            used[state] = handler if mode == 'full' else handler[:-2] + 'dp'
        for index, (state, handler) in enumerate(sorted(used.items())):
            body = body_of(text, f'void m68000_device::{handler}()').replace('m_irdi', 'opcode')
            # Labels have function scope even inside discarded constexpr arms.
            for label in re.findall(r'^(\w+):', body, re.M):
                body = re.sub(r'\b' + re.escape(label) + r'\b', f'aot_{state}_{label}', body)
            generated.append(f'{"if" if index == 0 else "else if"} constexpr (state == {state}) {{\n{body}\n}}')
        generated.append('}')
    generated.extend(['bool m68000_device::aot_dispatch(bool partial) {',
        'if (!sound_aot_enabled || m_mmu || debugger_enabled()) return false;',
        'if (m_inst_state < S_first_instruction) { ++sound_aot_events; return false; }',
        'using compiled_function = void (*)(m68000_device *);',
        'struct entry { uint16_t word, state; compiled_function full, partial; };',
        'static const entry entries[] = {'])
    for word, (state, _) in programs.items():
        generated.append(f'{{0x{word:04x}, {state}, &aot_thunk<0x{word:04x}, {state}, false>, &aot_thunk<0x{word:04x}, {state}, true>}},')
    generated.extend(['};', 'static const auto lookup = [] {',
        'std::array<const entry *, 65536> result{};',
        'for (const auto &value : entries) result[value.word] = &value;', 'return result;', '}();',
        'const auto code = lookup[m_irdi];',
        'if (!code || code->state != m_inst_state) { ++sound_aot_fallback; return false; }',
        'if (partial) { ++sound_aot_partial; code->partial(this); }',
        'else { ++sound_aot_hits; code->full(this); }', 'return true;', '}'])
    (OUT / 'virtual_on_m68000_program.ipp').write_text('\n'.join(generated) + '\n')
    header = replace_once(header, '\tinline void do_exec_full();', '''    template<uint16_t opcode, unsigned state> void aot_full();
    template<uint16_t opcode, unsigned state> void aot_partial();
    template<uint16_t opcode, unsigned state, bool partial> static void aot_thunk(m68000_device *cpu) {
        if constexpr (partial) cpu->aot_partial<opcode, state>();
        else cpu->aot_full<opcode, state>();
    }
    bool aot_dispatch(bool partial);
\tinline void do_exec_full();''')
    source = replace_once(source, '#include "m68000.h"',
                          '#include "m68000.h"\n#include <emscripten.h>\n#include "virtual_on_m68000_program.ipp"')
    source = replace_once(source, 'void m68000_device::device_start()\n{', '''void m68000_device::device_start()
{
    sound_aot_enabled = EM_ASM_INT({ return Module['model2ProgramAot'] === true && Module['model2SoundAot'] !== false; }) &&
        (!strcmp(machine().system().name, "vonu") || !strcmp(machine().system().name, "vonj"));
    sound_aot_hits = sound_aot_fallback = sound_aot_partial = sound_aot_events = 0;
    state_add(1100, "AOTENABLED", sound_aot_enabled).noshow();
    state_add(1101, "AOTHITS", sound_aot_hits).noshow();
    state_add(1102, "AOTFALLBACK", sound_aot_fallback).noshow();
    state_add(1103, "AOTPARTIAL", sound_aot_partial).noshow();
    state_add(1104, "AOTEVENTS", sound_aot_events).noshow();''')
    source = replace_once(source, '\t\tif(m_icount > 0 && m_inst_substate)\n\t\t\t(this->*(m_handlers_p[m_inst_state]))();',
                          '\t\tif(m_icount > 0 && m_inst_substate && !aot_dispatch(true))\n\t\t\t(this->*(m_handlers_p[m_inst_state]))();')
    source = replace_once(source, '\t\t\t(this->*(m_handlers_f[m_inst_state]))();',
                          '\t\t\tif (!aot_dispatch(false)) (this->*(m_handlers_f[m_inst_state]))();')
    write_cpu('m68000', 'cpp', source)
    write_cpu('m68000', 'h', header)
    return {'observedAddresses': len(corpus), 'reachableAddresses': len(reached), 'compiledInstructionWords': len(words),
            'imageSha256': hashlib.sha256(image).hexdigest(), 'analysis': result.stderr.strip()}


